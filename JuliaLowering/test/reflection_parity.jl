# ---------------------------------------------------------------- normalization
# Strip lane/gen module names; collapse counters inside gensym-ish tokens to N.
function _rp_norm(s::AbstractString)
    s = replace(s, r"mgen_[A-Za-z0-9_]+" => "MOD")
    # Canonicalize the function self-type rendering, which is binding-reachability
    # dependent (`typeof(Main.MOD.f)` vs `Main.MOD.var"#f"`).
    s = replace(s, r"(?:Main\.)?MOD\.var\"#([A-Za-z_][A-Za-z0-9_!]*)\"" => s"typeof(MOD.\1)")
    s = replace(s, "typeof(Main.MOD." => "typeof(MOD.")
    s = replace(s, r"[#\w]*#[#\w]*" => t -> replace(t, r"\d+" => "N"))
    return s
end
_rp_norm(x) = _rp_norm(string(x))
_rp_nsyms(v) = "[" * join((_rp_norm(x) for x in v), ", ") * "]"

# ---------------------------------------------------------------- extraction
_rp_argnames(m) = ccall(:jl_uncompress_argnames, Vector{Symbol}, (Any,), m.slot_syms)
_rp_hasfcall(m) = try Base.uncompressed_ir(m).has_fcall catch; missing end
_rp_slotflags(m) = try string(Int.(Base.uncompressed_ir(m).slotflags)) catch; "generated" end

function _rp_outer_methods(mod, primaries)
    ms = Any[]
    for p in primaries
        isdefined(mod, p) || continue
        v = Base.invokelatest(getglobal, mod, p)
        (v isa Function || v isa Type) || continue
        append!(ms, collect(methods(v)))
    end
    ms
end
_rp_kwcall_methods(mod) = [m for m in methods(Core.kwcall) if m.module === mod]

# Lower `code` through JuliaLowering and return the normalized layout record.
function _rp_record(code, primaries, modname)
    mod = Module(Symbol(modname))
    Core.eval(mod, :(using Base))
    Core.eval(mod, :(import Base: @kwdef, @nospecialize, @nospecializeinfer, @generated))
    JuliaLowering.include_string(mod, code)
    oms = _rp_outer_methods(mod, primaries)
    outer = sort([(sig=_rp_norm(m.sig), slot_syms=_rp_nsyms(_rp_argnames(m)),
                   nargs=Int(m.nargs), isva=m.isva,
                   kwarg_decl=_rp_nsyms(Base.kwarg_decl(m)),
                   has_fcall=_rp_hasfcall(m)) for m in oms], by=x->x.sig)
    kms = _rp_kwcall_methods(mod)
    kwcall = sort([(slot_syms=_rp_nsyms(_rp_argnames(m)), nargs=Int(m.nargs),
                    isva=m.isva, name=_rp_norm(m.name),
                    slotflags=_rp_slotflags(m)) for m in kms], by=x->x.slot_syms)
    nofs = String[]
    for p in primaries
        if isdefined(mod, p)
            v = Base.invokelatest(getglobal, mod, p)
            try; push!(nofs, _rp_norm(nameof(v))); catch; end
        end
    end
    return (outer=outer, kwcall=kwcall, nameof=nofs)
end

