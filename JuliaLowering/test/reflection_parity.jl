# ---------------------------------------------------------------- the fixture
@testset "reflection layout parity" begin
    @testset "$name" for (name, (code, primaries)) in _RP_SHAPES
        exp = _RP_EXPECTED[name]
        got = _rp_record(code, primaries, "mgen_$name")
        # Compare outer methods (Tissue / kwarg_decl / nameof consumer surfaces).
        @test isequal([NamedTuple(r) for r in got.outer], [NamedTuple(r) for r in exp.outer])
        # Compare internal kwcall method layout (pinned incl. known divergences).
        @test isequal([NamedTuple(r) for r in got.kwcall], [NamedTuple(r) for r in exp.kwcall])
        @test got.nameof == collect(exp.nameof)
    end
end
