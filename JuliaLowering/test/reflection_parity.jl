# Differential reflection-layout parity fixture.
#
# WHY THIS EXISTS
# ---------------
# flisp's raw lowered `Method`/`CodeInfo` layout is a de-facto public API:
# packages read slot names, `slot_syms` past `nargs`, gensym conventions, and
# CodeInfo flags directly (Tissue.jl reads `argnames[m.nargs:end]` off the outer
# Method; KeywordArgumentExtraction.jl reads `Base.kwarg_decl`). Over the course
# of the JuliaLowering compatibility work these surfaces were brought to parity
# one field at a time, each discovered by a PkgEval failure. This fixture pins
# the JL-lane layout for a matrix of method shapes so that any future drift in
# a reflective surface fails loudly here instead of in PkgEval.
#
# HOW IT WORKS
# ------------
# Each shape is lowered through JuliaLowering explicitly via
# `JuliaLowering.include_string` (so the pins hold regardless of whether the
# process lowerer is JL or flisp), then every introspectable layout surface is
# extracted, gensym-number- and module-name-normalized, and compared against a
# pinned expected value. The pins were generated by
# `~/pkgeval-JL-run/reflection-layout/gen_pins.jl` (kept alongside the one-time
# differential dump `dump.jl` / `diff-summary.txt`).
#
# WHAT IS PINNED, AND WHERE JL DIVERGES FROM flisp
# ------------------------------------------------
# The one-time differential dump (JL vs flisp, 34 shapes) found that every
# *consumer-facing* surface is already at parity:
#   * `Base.kwarg_decl`                       — parity on all shapes
#   * outer-method `slot_syms` / `method_argnames` (the Tissue surface) — parity
#   * `nameof` of top-level functions, user-method `show`, user-method CodeInfo
#     (incl. `has_fcall`)                     — parity
# The *only* residual divergences are confined to the internal `Core.kwcall`
# generated method and to one nested-closure naming case. They are pinned here
# at JL's CURRENT behavior (drift detection, not forced parity). Divergent cells
# are flagged inline below with `DIVERGES(flisp: ...)` and a workspace ref:
#
#   D1 kwcall slot naming: JL names the kwcall slots `kws`, `#kwtmp#`,
#      `#kwcall_self#`, `#unused#`; flisp uses `#s<N>`. This is
#      the `#kwtmp#` naming family (Cluster C, commit 9f1566ea2a;
#      bugs/kwtmp-ctor-leak). Benign: `Base.kwarg_decl` filters both to parity.
#      NOTE: the forwarded original-function self slot (a non-leading `#self#`)
#      is now blanked to `Symbol("")` to match flisp -- see the `to_code_info`
#      slotname pass in eval.jl (bugs/methodinspector-c2new). So the kwcall
#      `#self#` cells below now read `` (blank), matching the flisp reference.
#   D2 kwcall kw-slot ORDER differs (JL keeps declaration order + trailing
#      `#kwtmp#`; flisp interleaves an empty tmp cell). Internal to the kwcall
#      body; `kwarg_decl` is parity. Benign.
#   D3 kwcall `ci.slotflags`: JL emits 0 on the self/tmp slots where flisp marks
#      them used (8) / used+assigned (24). Recomputed by inference. Benign.
#   D4 (FIXED) kwcall `.name` for a nested kw closure now reports the closure's
#      OWN name (`h`), matching flisp, and the closure type name orders its
#      components own-first (`#h#outer4##N`). Previously JL reported the enclosing
#      function name (`outer4`) with the components reversed; that defeated
#      `Method.name`/`nameof`/`StackFrame.func` for any named local closure
#      (bugs/nested-closure-nameof: Pretend.jl keys `first(methods(f)).name`,
#      MIRTjim reads `stacktrace()[level].func`). Pinned here at the corrected
#      value; see `closure_type_basename` in closure_conversion.jl.
#   D5 `f(var"#self#") = 1`: flisp raises `syntax: function argument name not
#      unique: "#self#"`; JL accepts it (a second disambiguated `#self#` slot).
#      JL is *more* permissive, so no compiling package can depend on flisp's
#      error. Benign; pinned to catch future change in either direction.
#
# No class-(c) (consumer-plausible) divergence was found: the two historically
# consumer-visible surfaces (outer `slot_syms` = Tissue; `kwarg_decl` =
# KeywordArgumentExtraction) are now at parity, confirming those fixes converged.
#
# Ledger: ~/pkgeval-JL-run/bugs/reflection-layout-parity/notes.md

